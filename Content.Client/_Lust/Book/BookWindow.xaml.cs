namespace Content.Client._Lust.Book;

/// <summary>Displays book spreads and keeps page edits local until explicitly saved.</summary>
[GenerateTypedNameReferences]
public sealed partial class BookWindow : FancyWindow
{
    [Dependency] private IResourceCache _resourceCache = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private static readonly Type[] XmlAllowedTags =
    [
        typeof(BoldTag),
        typeof(ItalicTag),
        typeof(ColorTag),
        typeof(HeadingTag),
    ];
    private static readonly Color DefaultBookTextColor = new(25, 25, 25);

    private IReadOnlyList<BookPageData> _pages = Array.Empty<BookPageData>();
    private IReadOnlyList<string>? _rawPages;
    private readonly List<string> _draftPages = [];
    private readonly List<ProtoId<BookCoverPrototype>> _covers = [];
    private ProtoId<BookCoverPrototype>? _savedCover;
    private ProtoId<BookCoverPrototype>? _draftCover;
    private bool _editorAuthorized;
    private bool _updatingEditor;
    private int _maxPages;
    private int _contentSize;

    /// <summary>A complete draft snapshot ready to be submitted for server validation.</summary>
    public event Action<List<string>, ProtoId<BookCoverPrototype>>? OnSaved;

    /// <summary>Whether the local page draft is currently visible.</summary>
    public bool IsEditing { get; private set; }

    /// <summary>The zero-based draft page index, or -1 when no page is selected.</summary>
    public int SelectedPageIndex { get; private set; } = -1;

    /// <summary>The zero-based index of the currently visible spread.</summary>
    public int SpreadIndex { get; private set; }

    /// <summary>Empty books still have one blank spread.</summary>
    public int SpreadCount => Math.Max(1, (PageCount + 1) / 2);

    private int PageCount => _rawPages?.Count ?? _pages.Count;

    public BookWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PreviousButton.OnPressed += _ => TryPreviousSpread();
        NextButton.OnPressed += _ => TryNextSpread();
        EditButton.OnPressed += _ => TryBeginEditing();
        AddPageButton.OnPressed += _ => TryAddPage();
        SaveButton.OnPressed += _ => TrySave();
        CancelButton.OnPressed += _ => CancelEditing();
        PageSelector.OnItemSelected += args =>
        {
            if (args.ItemIndex != SelectedPageIndex)
                TrySelectPage(args.ItemIndex);
        };
        CoverSelector.OnItemSelected += args => TrySelectCover(_covers[args.Id]);
        PageEditor.OnTextChanged += _ =>
        {
            if (_updatingEditor || !IsEditing)
                return;

            StoreEditorPage();
            RefreshEditorLimits();
        };
        RefreshSpread();
    }

    /// <summary>Updates server permissions and limits without overwriting an active draft.</summary>
    public void UpdateEditor(BookComponent book, bool authorized)
    {
        var wasAuthorized = _editorAuthorized;
        _editorAuthorized = authorized && book.Editable && book.ContentPath == null;
        _maxPages = book.MaxPages;
        _contentSize = book.ContentSize;
        _savedCover = book.SelectedCover;
        _covers.Clear();
        CoverSelector.Clear();
        foreach (var cover in book.AvailableCovers)
        {
            if (_covers.Contains(cover) || !_prototype.TryIndex(cover, out var prototype))
                continue;

            CoverSelector.AddItem(_loc.GetString(prototype.Name), _covers.Count);
            _covers.Add(cover);
        }

        if (!_editorAuthorized)
        {
            CancelEditing();
            return;
        }

        if (!wasAuthorized)
            TryBeginEditing();

        RefreshCoverSelection();
        RefreshEditorLimits();
        EditButton.Visible = !IsEditing;
    }

    /// <summary>Starts a fresh draft from the latest authoritative dynamic pages.</summary>
    public bool TryBeginEditing()
    {
        if (!_editorAuthorized || IsEditing || _rawPages == null)
            return false;

        _draftPages.Clear();
        _draftPages.AddRange(_rawPages);
        _draftCover = _savedCover;
        if (_draftCover == null && _covers.Count > 0)
            _draftCover = _covers[0];

        IsEditing = true;
        ReaderContainer.Visible = false;
        EditorContainer.Visible = true;
        EditButton.Visible = false;
        SelectedPageIndex = -1;
        RefreshPageSelector();
        if (_draftPages.Count > 0)
            TrySelectPage(0);
        else
            DisplayEditorPage();
        RefreshCoverSelection();
        RefreshEditorLimits();
        return true;
    }

    /// <summary>Retains the current page's draft before selecting another page.</summary>
    public bool TrySelectPage(int index)
    {
        if (!IsEditing || index < 0 || index >= _draftPages.Count)
            return false;

        StoreEditorPage();
        SelectedPageIndex = index;
        PageSelector[index].Selected = true;
        DisplayEditorPage();
        return true;
    }

    /// <summary>Adds a blank page and selects it while the server's page limit permits.</summary>
    public bool TryAddPage()
    {
        if (!IsEditing || _draftPages.Count >= _maxPages)
            return false;

        StoreEditorPage();
        _draftPages.Add("");
        RefreshPageSelector();
        TrySelectPage(_draftPages.Count - 1);
        RefreshEditorLimits();
        return true;
    }

    /// <summary>Selects a cover from this book's permitted prototype list.</summary>
    public bool TrySelectCover(ProtoId<BookCoverPrototype> cover)
    {
        if (!IsEditing || !_covers.Contains(cover))
            return false;

        _draftCover = cover;
        RefreshCoverSelection();
        RefreshEditorLimits();
        return true;
    }

    /// <summary>Sends a complete draft snapshot; only a server update ends editing after save.</summary>
    public bool TrySave()
    {
        if (!IsEditing)
            return false;

        StoreEditorPage();
        RefreshEditorLimits();
        if (SaveButton.Disabled || _draftCover is not { } cover)
            return false;

        OnSaved?.Invoke(new List<string>(_draftPages), cover);
        return true;
    }

    /// <summary>Discards the draft and returns to the latest authoritative reader pages.</summary>
    public void CancelEditing()
    {
        IsEditing = false;
        _draftPages.Clear();
        _draftCover = null;
        SelectedPageIndex = -1;
        PageSelector.Clear();
        DisplayEditorPage();
        EditorContainer.Visible = false;
        ReaderContainer.Visible = true;
        EditButton.Visible = _editorAuthorized;
        RefreshSpread();
    }

    private void StoreEditorPage()
    {
        if (SelectedPageIndex >= 0 && SelectedPageIndex < _draftPages.Count)
            _draftPages[SelectedPageIndex] = Rope.Collapse(PageEditor.TextRope);
    }

    private void DisplayEditorPage()
    {
        _updatingEditor = true;
        PageEditor.TextRope = new Rope.Leaf(SelectedPageIndex >= 0 ? _draftPages[SelectedPageIndex] : "");
        PageEditor.CursorPosition = new TextEdit.CursorPos();
        PageEditor.Editable = IsEditing && SelectedPageIndex >= 0;
        _updatingEditor = false;
    }

    private void RefreshPageSelector()
    {
        PageSelector.Clear();
        for (var index = 0; index < _draftPages.Count; index++)
            PageSelector.AddItem(_loc.GetString("book-ui-page", ("number", index + 1)));
    }

    private void RefreshCoverSelection()
    {
        if (_draftCover is not { } cover || !_covers.Contains(cover))
        {
            if (_covers.Count > 0)
                _draftCover = _covers[0];
            else
                _draftCover = null;
        }

        if (_draftCover is { } selected)
            CoverSelector.SelectId(_covers.IndexOf(selected));
        CoverSelector.Disabled = _covers.Count == 0;
    }

    private void RefreshEditorLimits()
    {
        long length = 0;
        foreach (var page in _draftPages)
            length += page.Length;

        ContentSizeLabel.Text = _loc.GetString("book-ui-content-size", ("current", length), ("max", _contentSize));
        AddPageButton.Disabled = !IsEditing || _draftPages.Count >= _maxPages;
        SaveButton.Disabled = !IsEditing || _draftPages.Count > _maxPages || _contentSize < 0 ||
                              length > _contentSize || _draftCover is not { } cover || !_covers.Contains(cover);
    }

    /// <summary>Displays validated localized XML pages and content diagnostics.</summary>
    public void Populate(BookContentParseResult content)
    {
        _rawPages = null;
        _pages = content.Pages;
        SetError(ContentError, content.Error != null);
        RefreshSpread();
    }

    /// <summary>Displays a snapshot of dynamic pages using the paper rich-text allowlist.</summary>
    public void PopulatePages(IReadOnlyList<string> pages)
    {
        _rawPages = new List<string>(pages);
        _pages = Array.Empty<BookPageData>();
        SetError(ContentError, false);
        RefreshSpread();
    }

    /// <summary>Moves back one spread, returning false at the first spread.</summary>
    public bool TryPreviousSpread()
    {
        if (SpreadIndex == 0)
            return false;

        SpreadIndex--;
        RefreshSpread();
        return true;
    }

    /// <summary>Moves forward one spread, returning false at the last spread.</summary>
    public bool TryNextSpread()
    {
        if (SpreadIndex + 1 >= SpreadCount)
            return false;

        SpreadIndex++;
        RefreshSpread();
        return true;
    }

    private void RefreshSpread()
    {
        SpreadIndex = Math.Clamp(SpreadIndex, 0, SpreadCount - 1);
        PopulatePage(SpreadIndex * 2, LeftPageContent, LeftPageError);
        PopulatePage(SpreadIndex * 2 + 1, RightPageContent, RightPageError);
        LeftPageScroll.SetScrollValue(Vector2.Zero);
        RightPageScroll.SetScrollValue(Vector2.Zero);
        PreviousButton.Disabled = SpreadIndex == 0;
        NextButton.Disabled = SpreadIndex + 1 >= SpreadCount;
        SpreadLabel.Text = _loc.GetString("book-ui-spread", ("current", SpreadIndex + 1), ("total", SpreadCount));
    }

    private void PopulatePage(int index, BoxContainer container, RichTextLabel errorLabel)
    {
        container.DisposeAllChildren();
        SetError(errorLabel, false);
        if (index >= PageCount)
            return;

        if (_rawPages != null)
        {
            if (_rawPages[index].Length == 0)
                return;

            var message = new FormattedMessage();
            message.AddMarkupPermissive(_rawPages[index]);
            var label = CreateTextLabel();
            label.SetMessage(message, UserFormattableTags.BaseAllowedTags, DefaultBookTextColor);
            container.AddChild(label);
            return;
        }

        var page = _pages[index];
        if (page.Error != null)
        {
            SetError(errorLabel, true);
            return;
        }

        if (!TryPopulateBlocks(page.Nodes, container))
        {
            container.DisposeAllChildren();
            SetError(errorLabel, true);
        }
    }

    private bool TryPopulateBlocks(IReadOnlyList<BookPageNode> nodes, BoxContainer container)
    {
        FormattedMessage? textMessage = null;
        foreach (var node in nodes)
        {
            if (node is BookParagraphNode or BookHeadingNode)
            {
                var message = textMessage ??= new FormattedMessage();
                if (message.Nodes.Count > 0)
                    message.AddText("\n");

                switch (node)
                {
                    case BookParagraphNode paragraph:
                        AppendInline(message, paragraph.Children);
                        break;
                    case BookHeadingNode heading:
                        message.PushTag(new MarkupNode("head", new MarkupParameter(heading.Level), null));
                        if (heading.Level > 3)
                        {
                            // HeadingTag ограничивает размер третьим уровнем; продолжаем ту же
                            // шкалу через разрешённый BoldTag с фиксированным размером шрифта.
                            var size = (int) Math.Ceiling(FontTag.DefaultSize * 2 / Math.Sqrt(heading.Level));
                            message.PushTag(new MarkupNode("bold", null, new Dictionary<string, MarkupParameter>
                            {
                                ["size"] = new(size),
                            }));
                        }
                        AppendInline(message, heading.Children);
                        if (heading.Level > 3)
                            message.Pop();
                        message.Pop();
                        break;
                }

                continue;
            }

            FlushText();
            switch (node)
            {
                case BookImageNode image:
                    if (!_resourceCache.TryGetResource<TextureResource>(image.Source, out var texture))
                    {
                        // Существующий файл может оказаться повреждённой текстурой при загрузке.
                        Logger.WarningS("book", $"Cannot load book image '{image.Source}'.");
                        return false;
                    }

                    container.AddChild(new BookImageControl
                    {
                        Texture = texture.Texture,
                        Stretch = TextureRect.StretchMode.KeepAspectCentered,
                        CanShrink = true,
                        RectClipContent = true,
                        HorizontalExpand = true,
                        VerticalAlignment = Control.VAlignment.Top,
                    });
                    break;
                case BookHorizontalRuleNode:
                    container.AddChild(new HSeparator(DefaultBookTextColor) { HorizontalExpand = true });
                    break;
                case BookTableNode table:
                    container.AddChild(CreateTable(table));
                    break;
                case BookLayoutNode layout:
                    var layoutContainer = new BoxContainer
                    {
                        Orientation = BoxContainer.LayoutOrientation.Vertical,
                        HorizontalExpand = true,
                    };
                    container.AddChild(layoutContainer);
                    foreach (var row in layout.Rows)
                    {
                        var rowContainer = new BookLayoutRowContainer
                        {
                            Orientation = BoxContainer.LayoutOrientation.Horizontal,
                            HorizontalExpand = true,
                            SeparationOverride = 0,
                        };
                        layoutContainer.AddChild(rowContainer);
                        foreach (var column in row.Columns)
                        {
                            var columnContainer = new BoxContainer
                            {
                                Orientation = BoxContainer.LayoutOrientation.Vertical,
                                HorizontalExpand = true,
                                VerticalAlignment = Control.VAlignment.Top,
                            };
                            rowContainer.AddChild(columnContainer);
                            if (!TryPopulateBlocks(column.Children, columnContainer))
                                return false;
                        }
                    }
                    break;
            }
        }

        FlushText();
        return true;

        void FlushText()
        {
            if (textMessage == null)
                return;

            var label = CreateTextLabel();
            label.SetMessage(textMessage, XmlAllowedTags, DefaultBookTextColor);
            container.AddChild(label);
            textMessage = null;
        }
    }

    private static TableContainer CreateTable(BookTableNode table)
    {
        var columns = 1;
        foreach (var row in table.Rows)
            columns = Math.Max(columns, row.Cells.Count);

        var container = new TableContainer
        {
            Columns = columns,
            HorizontalExpand = true,
            // Отступы ячеек дают ненулевую ширину даже пустым таблицам; нулевой минимум
            // сохраняет ненулевой запас ширины при расчёте пропорций TableContainer.
            MinForcedColumnWidth = 0,
        };
        foreach (var row in table.Rows)
        {
            for (var index = 0; index < columns; index++)
            {
                var message = new FormattedMessage();
                if (index < row.Cells.Count)
                {
                    var cell = row.Cells[index];
                    if (cell.IsHeader)
                        message.PushTag(new MarkupNode("bold", null, null));
                    AppendInline(message, cell.Children);
                    if (cell.IsHeader)
                        message.Pop();
                }

                var label = CreateTextLabel();
                label.Margin = new Thickness(4, 2);
                label.SetMessage(message, XmlAllowedTags, DefaultBookTextColor);
                container.AddChild(label);
            }
        }

        return container;
    }

    private static RichTextLabel CreateTextLabel()
    {
        return new RichTextLabel
        {
            HorizontalExpand = true,
            StyleClasses = { "BookWrittenText" },
            VerticalAlignment = Control.VAlignment.Top,
        };
    }

    private static void AppendInline(FormattedMessage message, IReadOnlyList<BookPageNode> nodes)
    {
        foreach (var node in nodes)
        {
            // AddText сохраняет буквальный XML-текст, включая похожие на RichText теги строки.
            switch (node)
            {
                case BookTextNode text:
                    message.AddText(text.Text);
                    break;
                case BookLineBreakNode:
                    message.AddText("\n");
                    break;
                case BookBoldNode bold:
                    message.PushTag(new MarkupNode("bold", null, null));
                    AppendInline(message, bold.Children);
                    message.Pop();
                    break;
                case BookItalicNode italic:
                    message.PushTag(new MarkupNode("italic", null, null));
                    AppendInline(message, italic.Children);
                    message.Pop();
                    break;
                case BookColorNode color:
                    message.PushColor(color.Color);
                    AppendInline(message, color.Children);
                    message.Pop();
                    break;
            }
        }
    }

    private void SetError(RichTextLabel label, bool visible)
    {
        label.Visible = visible;
        if (visible)
            label.SetMessage(_loc.GetString("book-content-error"), DefaultBookTextColor);
    }

    private sealed class BookLayoutRowContainer : BoxContainer
    {
        protected override Vector2 MeasureOverride(Vector2 availableSize)
        {
            if (ChildCount == 0)
                return Vector2.Zero;

            // Обычный горизонтальный BoxContainer измеряет колонки по очереди;
            // длинный текст первой колонки не должен забирать ширину остальных.
            var columnSize = new Vector2(availableSize.X / ChildCount, availableSize.Y);
            var desired = Vector2.Zero;
            foreach (var child in Children)
            {
                child.Measure(columnSize);
                desired.X += child.DesiredSize.X;
                desired.Y = Math.Max(desired.Y, child.DesiredSize.Y);
            }

            return desired;
        }
    }

    private sealed class BookImageControl : TextureRect
    {
        protected override Vector2 MeasureOverride(Vector2 availableSize)
        {
            if (Texture == null)
                return Vector2.Zero;

            // CanShrink у TextureRect возвращает нулевую высоту внутри вертикальной страницы.
            var width = Math.Min(availableSize.X, Texture.Width);
            return new Vector2(width, width * Texture.Height / Texture.Width);
        }
    }
}
